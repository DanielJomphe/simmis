(ns is.simm.model.store
  "ONE definition of what a simmis store contains.

   simmis has two creators of datahike stores — dvergr provisions a room's
   messages/KB/data stores, and `knowledge-bases` creates user-owned shareable
   KBs — but only one KIND of store. Both install the same simmis half here, so
   a KB can hold a book and a room store can hold wiki pages, and neither
   acquires an attribute the other lacks by accident.

   What is deliberately NOT here: the per-store wiring whose MECHANISM differs
   by creator — fulltext index declaration, yggdrasil registration, the
   branching-broadcast listener. Those stay at their call sites.

   Store CONFIG (the create-time-fixed flags) is the other half of the same
   idea and lives in `dvergr.system.rooms/store-cfg` and
   `knowledge-bases/kb-datahike-cfg`. The one create-time flag all three
   share, `:diff-buf-size`, is `dvergr.substrate.datahike/diff-buf-size` — the
   same measurement, already defined once for every dvergr store, and simmis
   had grown a second copy of it."
  (:require [is.simm.model.schema :as schema]
            [is.simm.model.seed :as seed]
            [is.simm.model.accounting :as accounting]
            [is.simm.model.katzen-projection :as katzen-proj]
            [katzen.schema.knowledge :as kb-schema]
            [datahike.api :as d]
            [taoensso.telemere :as log]))

