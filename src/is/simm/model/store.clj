(defonce ^:private installed
  ;; store-id -> installed this process. See `ensure!`.
  (atom #{}))

(defn install!
  "Install simmis's half into `conn`'s store: the category-S schema, page-title
   uniqueness, the seed entities, late-added attributes, and the kontor book.
   Idempotent — schema transactions upsert on `:db/ident`.

   ORDER MATTERS. The category-S schema must land before anything that writes
   category-S entities: `accounting/ensure-accounting-schema!` reflects the
   ledger types into S, so it would otherwise transact `:entity/uuid` against a
   store that does not define it yet.

   Accounting is installed on EVERY store, not just rooms. That is the point of
   one store kind — a KB someone created for a project can grow a book without
   being re-created. `ensure-accounting-schema!` is cheap on repeat: it installs
   the kernel schema only when absent and otherwise just re-registers the
   process-local writer governor.

   `at` INSTALLS THE STORE AT THE BEGINNING OF ITS NARRATIVE TIME. Without it
   every transaction here is stamped `(Date.)` while seeded content is
   back-dated to the months the scenario describes (demo.scenario/provenance),
   so the store's own vocabulary is younger than its content: at a cut between
   the two, `[?e :instance/of-role [:entity/name \"S/Page\"]]` throws `Nothing
   found for entity id [:entity/name \"S/Page\"]` rather than returning nothing
   (measured 2026-07-27), and the whole workspace is unreadable at exactly the
   reference the demo wants to stand on. Pass the earliest instant any content
   in this store will claim; omit it for real tenants, where the install IS
   happening now.

   NOT everything reachable from here can be stamped. `kontor.core/install-schema!`
   and katzen's projection own their transactions and take no `:tx-meta`, so
   accounting's ~8s of kernel writes still land at wall clock. That is survivable
   where the seed is not, because nothing on a client READ path resolves a
   `:kontor.*` entity through a lookup ref — the only lookup refs the client
   renders through are the category-S role entities, which this does stamp."
  ([conn] (install! conn nil))
  ([conn at]
   ;; One transaction, and the uniqueness only when `:S.Page/title` does not yet
   ;; exist — see `page-title-unique-schema`. Both must land BEFORE the seed,
   ;; whose morphism->attribute machinery would otherwise declare the attribute
   ;; without uniqueness and make it un-alterable.
   (d/transact conn
               (cond-> {:tx-data (cond-> (vec schema/full-schema)
                                   (not (d/q '[:find ?e . :where [?e :db/ident :S.Page/title]] @conn))
                                   (into page-title-unique-schema))}
                 at (assoc :tx-meta {:db/txInstant at})))
   (seed/ensure-seed-data! conn at)
   (ensure-late-schema! conn)
   (project-kb-schema! conn)
   (accounting/ensure-accounting-schema! conn)
   conn))

(defn ensure!
  "`install!`, once per store per process. The guard is in memory, not in the
   store: everything `install!` does is idempotent, but it is a few hundred
   transactions' worth of work and rooms are hydrated in bulk at boot.

   `at` is the store's narrative install instant — see `install!`. It only ever
   applies to the FIRST install in this process, which is the create path; a
   later connect re-installs (if the guard is cold) at wall clock, correctly, as
   that write really is happening then."
  ([conn store-id] (ensure! conn store-id nil))
  ([conn store-id at]
   (when store-id
     (locking installed
       (when-not (contains? @installed store-id)
         (install! conn at)
         (swap! installed conj store-id)
         (log/log! {:level :info :id ::installed
                    :msg "simmis schema installed on store"
                    :data {:store-id store-id :at at}}))))
   conn))
