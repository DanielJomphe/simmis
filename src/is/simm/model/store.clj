(def page-title-unique-schema
  "`:S.Page/title` as a uniqueness constraint — the katzen title:Entity->Identity
   binding contract. The DATABASE enforces one page per title, so lookup refs,
   the AVET fast path and strict `datahike.reference` resolution all work.

   `:db.unique/value`, not `/identity`: a second page claiming an existing title
   is an ERROR to surface, not an upsert that silently merges two pages.

   NEW STORES ONLY. datahike rejects altering `:db/unique` on an existing
   attribute (it would need a dup-check plus an AVET backfill, unimplemented),
   and `:S.Page/title` is generated by the seed's morphism->attribute machinery
   without it. So this must be transacted BEFORE the seed and only when the
   attribute is absent; a store that predates it keeps the app-level dedup and
   resolves titles via `datahike.reference`'s explicit non-unique path."
  [{:db/ident :S.Page/title
    :db/valueType :db.type/string
    :db/cardinality :db.cardinality/one
    :db/unique :db.unique/value}])

(def kb-binding-opts
  "How katzen's `knowledge` schema binds onto category S — the binding functor
   of doc/kb-unification.md, in one place because every store applies the SAME
   binding and a second copy would drift.

   `:identify` — katzen's `Entity` IS the wiki page `S/Page`. No parallel
   `S/Entity` twin, and `title` projects onto the page title that already
   exists rather than duplicating it.

   `:storage-attrs` — `created-at`/`updated-at` are the UNIVERSAL entity
   timestamps every simmis entity already carries, not page-specific fields.
   Without this they would mint `:S.Page/created-at` alongside
   `:entity/created-at`: two attributes, one fact, and the page list reading
   the empty one."
  {:identify {:Entity "S/Page"}
   :storage-attrs {:Entity {:created-at :entity/created-at
                            :updated-at :entity/updated-at}}})

(defn project-kb-schema!
  "Project katzen's knowledge schema into this store's category S.

   Idempotent, and belongs on EVERY store: a KB store is where wiki pages
   actually live, so a KB whose S lacks `S/Page/summary` cannot render or query
   the property its own data carries. It ran only on the app store until now.

   Guarded — a projection failure degrades the categorical VIEW, it does not
   corrupt data, so it must not take down a store install."
  [conn]
  (try
    (katzen-proj/project-schema! conn kb-schema/schema kb-binding-opts)
    (catch Exception e
      (log/log! {:level :warn :id ::katzen-kb-project-failed
                 :msg "Could not project katzen KB schema into S"
                 :data {:error (.getMessage e)}})))
  conn)

(defn- ensure-late-schema!
  "Nothing. Kept as a named seam, with the reason it is empty.

   Every entry that lived here has moved into `schema/full-schema`, which
   `install!` re-transacts UNCONDITIONALLY on every store — so a migration
   function was never the mechanism that got attributes onto existing stores;
   `full-schema` already was. What the migration list actually did was decide
   which stores got the attribute at all: only those reached by this function,
   which is how three `:S.Message/*` attributes came to be missing from the app
   store while `columns.cljc` reads them in `:where` position against it.

   The rule this replaces: a NEW ATTRIBUTE GOES IN `full-schema`. If it cannot
   (a create-time-fixed flag like `:db/unique`), that is a store-config concern,
   not a migration — see `page-title-unique-schema`."
  [conn]
  conn)

